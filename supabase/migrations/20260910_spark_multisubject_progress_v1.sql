-- Generic, subject-scoped progress snapshots. New SPARK subjects can write to
-- this table through the RPCs below without adding subject-specific columns to
-- the dashboard or parent reporting schema.
create table if not exists public.spark_subject_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  subject_id text not null,
  activity_key text not null,
  activity_type text not null,
  section_id text,
  topic_id text,
  title text not null,
  completed boolean not null default false,
  score numeric(10,2),
  max_score numeric(10,2),
  percent numeric(6,2),
  best_percent numeric(6,2),
  attempt_count integer not null default 0 check (attempt_count >= 0),
  metadata jsonb not null default '{}'::jsonb,
  completed_at timestamptz,
  first_recorded_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, subject_id, activity_key),
  check (subject_id ~ '^[a-z0-9][a-z0-9_-]{0,39}$'),
  check (char_length(activity_key) between 1 and 120),
  check (activity_type in ('lesson','lab','flashcard','topic_quiz','section_checkpoint','exam','practice','other')),
  check (percent is null or percent between 0 and 100),
  check (best_percent is null or best_percent between 0 and 100),
  check (max_score is null or max_score >= 0),
  check (score is null or score >= 0)
);

