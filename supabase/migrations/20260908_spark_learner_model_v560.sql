create or replace function public.spark_capture_csec_question_attempt()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v jsonb := to_jsonb(new);
  v_user uuid;
  v_skill text;
  v_correct boolean;
  v_item text;
  v_key text;
  v_difficulty text;
  v_error_code text;
  v_error_label text;
  v_seconds integer;
  v_help boolean;
begin
  begin v_user := nullif(v ->> 'user_id', '')::uuid; exception when others then return new; end;
  v_skill := coalesce(nullif(v ->> 'skill', ''), nullif(v ->> 'topic', ''), nullif(v ->> 'subtopic', ''));
  if v_user is null or v_skill is null then return new; end if;

  begin
    v_correct := coalesce(nullif(v ->> 'correct', '')::boolean, nullif(v ->> 'is_correct', '')::boolean, false);
  exception when others then
    v_correct := false;
  end;
  v_item := coalesce(nullif(v ->> 'question_id', ''), nullif(v ->> 'item_id', ''), nullif(v ->> 'id', ''));
  v_key := coalesce(nullif(v ->> 'id', ''), md5(v::text));
  v_difficulty := nullif(v ->> 'difficulty', '');
  v_error_code := coalesce(nullif(v ->> 'error_code', ''), nullif(v ->> 'misconception', ''), nullif(v ->> 'mistake_code', ''));
  v_error_label := coalesce(nullif(v ->> 'error_label', ''), nullif(v ->> 'misconception_label', ''));
  begin v_seconds := nullif(v ->> 'response_seconds', '')::integer; exception when others then v_seconds := null; end;
  begin v_help := coalesce(nullif(v ->> 'help_used', '')::boolean, false); exception when others then v_help := false; end;

  perform public.spark_apply_learner_evidence(
    v_user, v_skill, coalesce(nullif(v ->> 'source', ''), 'adaptive_practice'),
    v_item, v_correct, 1, v_difficulty, v_seconds, v_help, v_error_code, v_error_label,
    jsonb_build_object('captured_by', 'csec_question_attempts_trigger'), v_key,
    coalesce(nullif(v ->> 'attempted_at', '')::timestamptz, now())
  );
  return new;
exception when others then
  -- Learner modelling must never prevent the original practice attempt saving.
  raise warning 'SPARK learner model capture failed: %', sqlerrm;
  return new;
end;
$$;

do $$
begin
  if to_regclass('public.csec_question_attempts') is not null then
    execute 'drop trigger if exists spark_capture_learner_evidence on public.csec_question_attempts';
    execute 'drop trigger if exists zz_spark_capture_learner_evidence on public.csec_question_attempts';
    -- The zz prefix intentionally runs this after existing AFTER INSERT triggers,
    -- so the compatibility mastery bridge is the final mastery signal written.
    execute 'create trigger zz_spark_capture_learner_evidence after insert on public.csec_question_attempts for each row execute function public.spark_capture_csec_question_attempt()';
  end if;
end;
$$;

-- Seed the new model from the mastery SPARK already has. This preserves each
-- student's history instead of treating V5.6.0 as a blank start.
do $$
declare
  r record;
  v jsonb;
  v_probability numeric;
  v_attempts integer;
begin
  if to_regclass('public.csec_skill_progress') is null then return; end if;
  for r in execute 'select * from public.csec_skill_progress' loop
    v := to_jsonb(r);
    if nullif(v ->> 'user_id', '') is null or nullif(v ->> 'skill', '') is null then continue; end if;
    begin
      v_probability := greatest(0.01, least(0.99, coalesce(nullif(v ->> 'mastery_score', '')::numeric, 50) / 100.0));
    exception when others then
      v_probability := 0.5;
    end;
    begin
      v_attempts := greatest(1, coalesce(
        nullif(v ->> 'attempt_count', '')::integer,
        nullif(v ->> 'attempts', '')::integer,
        nullif(v ->> 'total_attempts', '')::integer,
        1
      ));
    exception when others then
      v_attempts := 1;
    end;

    insert into public.spark_learner_skill_state (
      user_id, skill, mastery_probability, confidence, evidence_count,
      correct_weight, incorrect_weight, recent_score, trend_score,
      last_practised_at, last_source, recommended_action
    ) values (
      (v ->> 'user_id')::uuid,
      v ->> 'skill',
      v_probability,
      least(0.85, 1 - exp(-v_attempts / 6.0)),
      v_attempts,
      v_attempts * v_probability,
      v_attempts * (1 - v_probability),
      v_probability,
      0,
      coalesce(nullif(v ->> 'updated_at', '')::timestamptz, nullif(v ->> 'last_attempted_at', '')::timestamptz, now()),
      'existing_mastery',
      case
        when v_probability < 0.45 then 'Review the lesson, then do targeted Adaptive Practice and related flashcards.'
        when v_probability < 0.60 then 'Use targeted Adaptive Practice and flashcards before moving to harder questions.'
        when v_probability < 0.75 then 'Mix targeted practice with harder questions to make the skill more reliable.'
        when v_probability < 0.85 then 'Use spaced review and exam-style questions to strengthen consistency.'
        else 'Maintain this skill with spaced review while SPARK shifts attention to weaker areas.'
      end
    ) on conflict (user_id, skill) do nothing;
  end loop;
end;
$$;
