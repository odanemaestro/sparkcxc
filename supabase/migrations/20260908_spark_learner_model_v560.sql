create or replace function public.spark_record_learner_evidence(
  p_skill text,
  p_source text,
  p_item_id text default null,
  p_correct boolean default false,
  p_evidence_weight numeric default 1,
  p_difficulty text default null,
  p_response_seconds integer default null,
  p_help_used boolean default false,
  p_error_code text default null,
  p_error_label text default null,
  p_metadata jsonb default '{}'::jsonb,
  p_evidence_key text default null,
  p_occurred_at timestamptz default now()
)
returns public.spark_learner_skill_state
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
begin
  if v_user is null then
    raise exception 'Authentication required';
  end if;
  return public.spark_apply_learner_evidence(
    v_user, p_skill, p_source, p_item_id, p_correct, p_evidence_weight,
    p_difficulty, p_response_seconds, p_help_used, p_error_code, p_error_label,
    p_metadata, p_evidence_key, p_occurred_at
  );
end;
$$;

