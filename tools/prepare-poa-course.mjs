import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
const bundled = await build({
  stdin: {
    contents:
      'export * from "./src/principlesOfAccounts/data/poaCourse.js";export * from "./src/principlesOfAccounts/data/poaPaper2.js";',
    resolveDir: process.cwd(),
  },
  bundle: true,
  write: false,
  format: "esm",
  platform: "node",
});
const data = await import(
  "data:text/javascript;base64," +
    Buffer.from(bundled.outputFiles[0].text).toString("base64")
);
const quote = (v) => "'" + String(v).replaceAll("'", "''") + "'";
const json = (v) => quote(JSON.stringify(v)) + "::jsonb";
const subject = "principles-of-accounts";
const subjectRow = {
  id: subject,
  name: "CSEC Principles of Accounts",
  short_name: "Principles of Accounts",
  qualification: "CSEC",
  mark: "PA",
  description:
    "Clear accounting notes, original practice, source papers and a connected accounting workspace.",
  enabled: false,
  status: "draft",
  sort_order: 49,
  implementation: "generic",
  study_view: "study",
  capabilities: {
    study: true,
    practice: true,
    flashcards: true,
    progress: true,
    paper1: true,
    paper2: true,
    adaptive: false,
    structured: true,
    labs: true,
    sba: true,
  },
  routes: {
    study: "/study/" + subject,
    practice: "/practice/" + subject,
    flashcards: "/dashboard/flashcards/" + subject,
    progress: "/dashboard/progress",
  },
  stats: {
    sections: 11,
    topics: 33,
    objectives: 106,
    flashcards: 66,
    paper1OriginalQuestions: 60,
    paper2OriginalPapers: 1,
    historicalFiles: 51,
    distinctHistoricalPdfs: 50,
    verifiedHistoricalKeys: 0,
  },
  learning_config: {
    syllabusCode: data.POA_SYLLABUS,
    syllabusUrl: data.POA_SYLLABUS_URL,
    exam: data.POA_EXAM,
    releaseStage: "course-review-historical-calibration-pending",
    prerequisites: data.POA_TOPICS.slice(1).map((t, i) => ({
      topicId: t.id,
      requires: [data.POA_TOPICS[i].id],
    })),
  },
  manifest_version: 1,
};
const value = (v) =>
  typeof v === "object"
    ? json(v)
    : typeof v === "boolean" || typeof v === "number"
      ? String(v)
      : quote(v);
let sql =
  "-- Generated by node tools/prepare-poa-course.mjs. Draft course; does not publish or enrol anyone.\nbegin;\n";
sql += `insert into public.spark_subjects (${Object.keys(subjectRow).join(",")}) values (${Object.values(subjectRow).map(value).join(",")})\non conflict(id) do update set name=excluded.name,short_name=excluded.short_name,description=excluded.description,sort_order=excluded.sort_order,implementation=excluded.implementation,study_view=excluded.study_view,capabilities=excluded.capabilities,routes=excluded.routes,stats=excluded.stats,learning_config=excluded.learning_config,manifest_version=greatest(public.spark_subjects.manifest_version,excluded.manifest_version),updated_at=now();\n`;
// An existing operator's enabled/status choices survive rerunning the content seed.
for (const section of data.POA_SECTIONS)
  sql += `insert into public.spark_subject_sections(subject_id,section_id,title,description,sort_order,enabled,metadata) values (${[subject, section.id, section.title, section.description, section.sortOrder, true, section.metadata].map(value).join(",")}) on conflict(subject_id,section_id) do update set title=excluded.title,description=excluded.description,sort_order=excluded.sort_order,metadata=excluded.metadata,updated_at=now();\n`;
for (const topic of data.POA_TOPICS)
  sql += `insert into public.spark_subject_topics(subject_id,topic_id,section_id,title,description,sort_order,enabled,metadata) values (${[subject, topic.id, topic.sectionId, topic.title, topic.description, topic.sortOrder, true, topic.metadata].map(value).join(",")}) on conflict(subject_id,topic_id) do update set title=excluded.title,description=excluded.description,section_id=excluded.section_id,sort_order=excluded.sort_order,metadata=excluded.metadata,updated_at=now();\n`;
sql += `insert into spark_grading_private.rubrics_v2(subject_id,rubric_version,paper_id,criteria,active,verification_status,expected_total_marks) values (${quote(subject)},${quote(data.POA_PAPER2_RUBRIC_VERSION)},${quote(data.POA_PAPER2_ID)},${json(data.poaPaper2Criteria())},false,'draft',100) on conflict(subject_id,rubric_version,paper_id) do nothing;\ncommit;\n`;
fs.writeFileSync(
  "supabase/migrations/20261021090000_principles_of_accounts_course_draft.sql",
  sql,
);
const coverage = [
  "# Principles of Accounts syllabus coverage",
  "",
  `Source: ${data.POA_SYLLABUS} (${data.POA_SYLLABUS_URL}).`,
  "",
  "106 objectives mapped to 33 lessons in 11 sections. Mapping records where content is taught; it is not an assertion of historical answer-key calibration.",
  "",
  "| Objective | Syllabus page | Lesson |",
  "| --- | --- | --- |",
  ...data.POA_COVERAGE.map(
    (o) =>
      `| ${o.code}: ${o.title} | ${o.sourcePage} | ${o.lessonIds.join(", ")} |`,
  ),
];
fs.writeFileSync(
  "docs/principles-of-accounts-coverage.md",
  coverage.join("\n") + "\n",
);
console.log(
  "Prepared Accounts migration, private draft V2 rubric and 106-objective coverage map.",
);
