import fs from "node:fs";
import {build} from "esbuild";

// Regenerate only the two CLI-created Accounts method migrations. No database
// connection or release is performed here; every seeded rubric stays draft.
const migrationDir="supabase/migrations/";
const file=(suffix)=>{
 const matches=fs.readdirSync(migrationDir).filter(name=>name.endsWith(suffix));
 if(matches.length!==1)throw Error(`Expected one CLI-created ${suffix}`);
 return migrationDir+matches[0];
};
const b=await build({stdin:{contents:`export * from './src/principlesOfAccounts/marking/poaMethodRegistry.js';
 export * from './src/principlesOfAccounts/data/poaHistoricalPaper2.js';
 export * from './src/principlesOfAccounts/data/poaSpecimenPaper2.js';`,resolveDir:process.cwd()},bundle:true,write:false,format:"esm",platform:"node"});
const d=await import("data:text/javascript;base64,"+Buffer.from(b.outputFiles[0].text).toString("base64"));
const papers=d.poaMethodPapers();
if(papers.length!==94||d.POA_METHOD_QUESTION_POLICIES.length!==171)throw Error("Accounts method source coverage changed");
const quote=s=>"'"+String(s).replaceAll("'","''")+"'";
const array=a=>`array[${a.join(",")}]::integer[]`;
const sources=[...d.POA_HISTORICAL_PAPER2_ARCHIVE,d.POA_SPECIMEN_PAPER2];
const catalog=sources.map(p=>{
 const c=p.choicePolicy||{type:"all"};
 return `(${quote(p.id)},${quote(p.sourceSha256)},${array(c.type==="all"?p.questions.map(q=>q.number):c.compulsory)},${array(c.type==="all"?[]:c.from)},${c.type==="all"?0:c.choose},${array(p.questions.map(q=>q.number))})`;
}).join(",\n");
const destination=file("_marking_v2_poa_source_methods.sql");
const runtime=fs.readFileSync("tools/poa-method-release.sql","utf8");
fs.writeFileSync(destination,`-- Generated by tools/prepare-poa-method-rubrics.mjs. SPARK-authored policy.\nbegin;\n
create table if not exists spark_grading_private.poa_method_sources_v2 (
 source_paper_id text primary key, source_pdf_sha256 text not null check(source_pdf_sha256 ~ '^[a-f0-9]{64}$'),
 compulsory integer[] not null, optional integer[] not null, choose_count integer not null check(choose_count between 0 and 2),
 question_numbers integer[] not null
);
alter table spark_grading_private.poa_method_sources_v2 enable row level security;
revoke all on spark_grading_private.poa_method_sources_v2 from public,anon,authenticated,service_role;
grant select on spark_grading_private.poa_method_sources_v2 to service_role;
insert into spark_grading_private.poa_method_sources_v2 values\n${catalog}\non conflict(source_paper_id) do nothing;\n${runtime}\ncommit;\n`);
const inserts=papers.map(p=>{
 const criteria=quote(JSON.stringify(p.criteria))+"::jsonb";
 return `insert into spark_grading_private.rubrics_v2(subject_id,paper_id,rubric_version,criteria,expected_total_marks,active,verification_status,source_sha256) select 'principles-of-accounts',${quote(p.paperId)},${quote(p.rubricVersion)},c,100,false,'draft',encode(pg_catalog.sha256(convert_to(c::text,'UTF8')),'hex') from (select ${criteria} c) source on conflict(subject_id,rubric_version,paper_id) do nothing;`;
}).join("\n");
fs.writeFileSync(file("_marking_v2_poa_method_rubrics.sql"),`-- Generated by tools/prepare-poa-method-rubrics.mjs.\n-- Source caps are printed; atomic allocations and interpretations are SPARK-authored.\n-- All 94 five-question selections remain inactive until actual V2 evidence passes.\nbegin;\n${inserts}\ncommit;\n`);
console.log(JSON.stringify({sources:sources.length,questionPolicies:d.POA_METHOD_QUESTION_POLICIES.length,variants:papers.length,criteria:papers.reduce((n,p)=>n+p.criteria.length,0),seedBytes:fs.statSync(file("_marking_v2_poa_method_rubrics.sql")).size}));
