export function normaliseITAnswer(value) {
  return String(value ?? "")
    .toLowerCase()
    .replace(/[−–—]/g, "-")
    .replace(/[“”]/g, '"')
    .replace(/[‘’]/g, "'")
    .replace(/&/g, " and ")
    .replace(/\bfiber\b/g, "fibre")
    .replace(/\bwi[ -]?fi\b/g, "wifi")
    .replace(/\s+/g, " ")
    .trim();
}

export function phrasePresent(answer, phrase) {
  const haystack = normaliseITAnswer(answer);
  const needle = normaliseITAnswer(phrase);
  if (!haystack || !needle) return false;
  if (haystack.includes(needle)) return true;
  const words = needle.split(/[^a-z0-9$]+/).filter(Boolean);
  return words.length > 1 && words.every(word => haystack.includes(word));
}

export function conceptPresent(answer, key) {
  const phrases = IT_CANONICAL_CONCEPTS[key] || [key];
  return phrases.some(phrase => phrasePresent(answer, phrase));
}

export function conceptsPresent(answer, keys = []) {
  return keys.filter(key => conceptPresent(answer, key));
}
